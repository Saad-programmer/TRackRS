"""Generate docs/CARS.md: every car, its class pack, model status, licence,
verified metadata and the measured per-car GPU cost.

Sources (read only): data/vehicles/<id>/car.json and the legacy
<id>.vehicle files, data/packs/*/vehicles/<id>/car.json, the pack manifests,
and the per-car measurements in docs/reports/phase4d/cars.json (written by
tools/car_render_report.py; missing cars show "not measured").
Usage: tools/gen_cars_md.py [--check]
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/CARS.md'
MEASURED = ROOT / 'docs/reports/phase4d/cars.json'
CLASS_ORDER = ['class-rally-raid', 'morocco-sahara', 'class-heritage-raid', 'rally-roster']
CLASS_TITLE = {'class-rally-raid': '1. Rally-raid (`class-rally-raid`)',
               'morocco-sahara': '1b. Rally-raid, fictional event cars (`morocco-sahara`)',
               'class-heritage-raid': '2. Heritage raid (`class-heritage-raid`)',
               'rally-roster': '3. Existing rally roster (`data/vehicles`, kept in place)'}


def legacy_info(path):
    text = path.read_text(errors='replace')
    name = re.search(r'name="([^"]*)"', text)
    cls = re.search(r'class="([^"]*)"', text)
    return (name.group(1) if name else path.stem), (cls.group(1) if cls else '')


def cars():
    out = []
    for d in sorted((ROOT / 'data/vehicles').iterdir()):
        if d.name == 'pbr_test':
            continue
        cj, vf = d / 'car.json', d / f'{d.name}.vehicle'
        if cj.exists():
            out.append(('rally-roster', d.name, json.loads(cj.read_text())))
        elif vf.exists():
            name, cls = legacy_info(vf)
            out.append(('rally-roster', d.name, {'legacy': True, 'display_name': name, 'class': cls}))
    for pack in sorted((ROOT / 'data/packs').iterdir()):
        for cj in sorted(pack.glob('vehicles/*/car.json')):
            out.append((pack.name, f'{pack.name}:{cj.parent.name}', json.loads(cj.read_text())))
    return out


def verified(car):
    v = car.get('verified', {})
    done = [k for k, ok in sorted(v.items()) if ok]
    return f'{len(done)}/{len(v)}' + (f' ({", ".join(done)})' if done else '')


def model(car):
    if car.get('legacy'):
        return 'own legacy mesh (fictional)'
    mesh = car.get('body', {}).get('mesh', '')
    if mesh:
        return f'`{mesh}` ({car["license"].get("model", "?")})'
    return f'**placeholder model** (borrows `{car["body"]["fallback"]}`)'


def measured(data, cid):
    m = data.get(cid)
    if not m:
        return 'not measured', ''
    return f'{m["gpu_bytes"] / 2**20:.2f}', f'{m["cars_cpu_ms"]:.2f} / {m["shadow_cars_cpu_ms"]:.2f}'


def render():
    data = json.loads(MEASURED.read_text())['cars'] if MEASURED.exists() else {}
    groups = {}
    for group, cid, car in cars():
        groups.setdefault(group, []).append((cid, car))
    total = sum(len(v) for v in groups.values())
    placeholders = sum(1 for v in groups.values() for _, c in v if not c.get('legacy') and not c.get('body', {}).get('mesh'))
    lines = ['# Cars', '',
             '<!-- Generated by tools/gen_cars_md.py from the car files, pack manifests and '
             'docs/reports/phase4d/cars.json. Do not edit by hand. -->', '',
             f'{total} cars. {placeholders} of them still wait for a mesh and show as "(placeholder model)". '
             'Mesh specification: [ASSET_SOURCING.md](ASSET_SOURCING.md). Data format: '
             '[CAR_DEFINITION.md](CAR_DEFINITION.md).', '',
             '* **Figures:**',
             '  * `verified` counts the six data groups (mass, engine, gearbox, tyres, aero, brakes) that cite a source.',
             '  * The class packs carry **class-typical placeholder figures, not the named cars\' data**.',
             '  * The 4a roster carries unverified seeds.',
             '  * Each `car.json` provenance says which.',
             '* **Cost** (Phase 4d measurement, `tools/car_render_report.py`):',
             '  * Setup: llvmpipe software GL, 640×480, medium, CSM, noon, stage `ahead`, 24 frames.',
             '  * **VRAM** is the renderer\'s own accounting for the car type.',
             '  * **CPU ms** is the `cars` / `shadow_cars` pass wall time per frame, which under software GL includes rasterisation queueing.',
             '  * Hardware numbers are still owed.', '']
    for group in CLASS_ORDER:
        if group not in groups:
            continue
        lines += [f'## {CLASS_TITLE[group]}', '',
                  '| id | car | class | model | licence (data) | verified | trademark notice | VRAM MB | CPU ms cars / shadows |',
                  '|---|---|---|---|---|---|---|---|---|']
        for cid, car in groups[group]:
            if car.get('legacy'):
                lic, ver, tm = 'GPL-2.0-or-later (legacy Trigger Rally data)', 'n/a (fictional legacy car)', '—'
            else:
                lic = car['license']['data']
                ver = verified(car)
                tm = 'yes' if car['license'].get('trademark_notice') else '— (fictional)'
            vram, ms = measured(data, cid)
            name = car['display_name'] + ('' if car.get('legacy') or car.get('body', {}).get('mesh') else ' (placeholder model)')
            lines.append(f'| `{cid}` | {name} | {car.get("class", "")} | {model(car)} | {lic} | {ver} | {tm} | {vram} | {ms} |')
        lines.append('')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit('docs/CARS.md is stale: run tools/gen_cars_md.py')
        print('PASS: docs/CARS.md is up to date')
        return
    OUT.write_text(text, encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
