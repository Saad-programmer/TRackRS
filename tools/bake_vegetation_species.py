"""Regenerate data/vegetation/species.json from the shipped legacy sprites.

The 3D vegetation meshes are procedural (engine/vegetation/vegetation.cpp); this
tool only records, per legacy sprite, which procedural form replaces it and the
mean sRGB colour of the sprite's opaque texels so near meshes and far impostor
cards share one palette. No external artwork is read or produced.
Colour = mean of the brighter half (by luminance) of the opaque texels.
Usage: tools/bake_vegetation_species.py [--check]
"""
import argparse, json, pathlib, sys
try:
    from PIL import Image
except ImportError:  # CI images without Pillow can still verify coverage
    Image = None
ROOT = pathlib.Path(__file__).resolve().parents[1]
SPRITES = ROOT / 'data/textures/veg'
OUTPUT = ROOT / 'data/vegetation/species.json'
FORMS = {
    'conifer': ['fir', 'spruce', 'spruce-little', 'needle', 'snowy-spruce'],
    'broadleaf': ['birch', 'brown-tree', 'color-tree7', 'fine-tree', 'green-tree', 'green-tree2',
                  'horse-chestnut-tree', 'pear-tree', 'purple-leaf-plum', 'red-tree', 'thick-tree',
                  'wide-tree', 'wide-tree2', 'willow'],
    'bush': ['bush-low', 'bush', 'olive-bush', 'thick-leafes', 'thorn-bush', 'dusty-bush', 'bush-ash'],
    'grass': ['grass', 'grass-sprite', 'grass2', 'dry-grass', 'herbs', 'grain', 'mais'],
    'palm': ['palm-tree', 'palm-tree2', 'palm3', 'palm4', 'palmy'],
    'cactus': ['cactus1'],
    # Sparse/bare silhouettes, posts and climbers have no faithful procedural
    # form yet: they stay as (instanced) cards at every distance.
    'card': ['big-bush', 'bush-dry', 'crooked-tree1', 'crooked-tree2', 'crooked-tree3', 'crooked-tree4',
             'crooked-tree5', 'dry-slim-bush1', 'dry-slim-bush2', 'thin-bush', 'first-branch', 'ivy', 'post',
             'tree-shape1', 'tree-shape2', 'tree-shape3', 'tree-shape4', 'tree-shape5', 'tree-shape6',
             'tree-shape7', 'snowy-tree', 'bland-birch', 'berry-bush'],
}
BARK = {'birch': '#d6d0c2', 'palm': '#7d6a50', 'cactus': None}
def width(path):
    """Opaque content width as a fraction of the card width (alpha > 50%)."""
    image = Image.open(path).convert('RGBA')
    image.thumbnail((256, 256))
    box = image.split()[3].point(lambda v: 255 if v > 128 else 0).getbbox()
    return round((box[2] - box[0]) / image.size[0], 2) if box else 1.0
def mean(path):
    image = Image.open(path).convert('RGBA')
    image.thumbnail((128, 128))
    pixels = image.get_flattened_data() if hasattr(image, 'get_flattened_data') else image.getdata()
    opaque = sorted((p[:3] for p in pixels if p[3] > 128), key=lambda c: 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2])
    # Brighter half only: the sprite's dark texels are baked self-shadow and
    # gaps, which the 3D mesh reproduces with real lighting and CSM.
    lit = opaque[len(opaque) // 2:] or [(128, 128, 128)]
    return '#%02x%02x%02x' % tuple(round(sum(c[i] for c in lit) / len(lit)) for i in range(3))
def build():
    lookup = {name: form for form, names in FORMS.items() for name in names}
    sprites = {}
    for path in sorted(SPRITES.glob('*.png')):
        stem = path.stem
        if stem not in lookup:
            raise SystemExit(f'unmapped vegetation sprite: {path.name}')
        form = lookup[stem]
        entry = {'form': form, 'foliage': mean(path), 'width': width(path)}
        bark = BARK.get('birch' if 'birch' in stem else form, '#4a3a2a')
        if form not in ('card', 'grass') and bark:
            entry['bark'] = bark
        sprites[path.name] = entry
    missing = set(lookup) - {p.stem for p in SPRITES.glob('*.png')}
    if missing:
        raise SystemExit(f'mapped sprites missing on disk: {sorted(missing)}')
    return {'schema': 'trackrs.vegetation/1',
            'license': 'GPL-2.0-or-later',
            'provenance': 'Form assignments and procedural mesh parameters are authored for TrackRS. Foliage colours are measured mean sRGB values of the opaque texels of the shipped sprites named as keys; those sprites keep the licenses listed in doc/DATA_AUTHORS.txt. No artwork is copied. Generated by tools/bake_vegetation_species.py.',
            'sprites': sprites}
def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    if args.check and Image is None:
        stored = json.loads(OUTPUT.read_text())['sprites']
        names = {p.name for p in SPRITES.glob('*.png')}
        lookup = {name for names_ in FORMS.values() for name in names_}
        if set(stored) != names or {pathlib.Path(n).stem for n in names} != lookup:
            sys.exit('species.json does not cover exactly the shipped sprites')
        print('PASS: species.json covers every sprite (Pillow unavailable: colours not re-measured)'); return
    text = json.dumps(build(), indent=1, sort_keys=True) + '\n'
    if args.check:
        if OUTPUT.read_text() != text:
            sys.exit('species.json is stale; run tools/bake_vegetation_species.py')
        print('PASS: species.json matches sprites'); return
    OUTPUT.write_text(text); print(f'wrote {OUTPUT.relative_to(ROOT)}')
if __name__ == '__main__': main()
