"""Record original procedural fixture provenance without claiming external art."""
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def write(output):
    names = json.loads((output/'surfaces.json').read_text())['layers']
    tree = ast.parse((ROOT/'tools/bake_terrain_materials.py').read_text())
    recipes = next(ast.literal_eval(n.value) for n in ast.walk(tree) if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'surfaces' for t in n.targets))
    contrasts = [.04,.25,.18,.22,.08,.03,.04,.13,.02]
    sets = []
    for layer, name in enumerate(names):
        files = [output/f'{name}-{kind}.{ext}' for kind in ('albedo','normal','orm') for ext in ('png','ktx2')]
        files.append(output/f'{name}.material.json')
        sets.append({'name':name, 'author':'TrackRS project; procedural fixtures generated by OpenAI Codex during Phase 3a',
                     'spdx':'CC0-1.0', 'source':'Original analytic generation in tools/bake_terrain_materials.py; no downloaded artwork',
                     'seed':layer+31, 'method':'64x64 periodic seeded value noise at periods 4/8/16/32, weights .40/.30/.20/.10. Albedo uses the per-surface RGB/contrast recipe; tangent normals use central differences of that noise and the per-surface strength; ORM packs AO=1, noise-varied roughness, metallic=0. bake-material creates full mip chains and BC7 sRGB albedo, BC5 linear normals and BC7 linear ORM KTX2.',
                     'recipe':{'generator':'tools/bake_terrain_materials.py','layer':layer},
                     'parameters':{'base_rgb_srgb8':recipes[layer][1], 'roughness':recipes[layer][2], 'normal_strength':recipes[layer][3], 'albedo_contrast':contrasts[layer]},
                     'files':{p.name:digest(p) for p in files}})
    result={'schema':'trackrs.terrain-provenance/1', 'license':'CC0-1.0.txt',
            'license_url':'https://creativecommons.org/publicdomain/zero/1.0/legalcode',
            'generator_sha256':digest(ROOT/'tools/bake_terrain_materials.py'), 'sets':sets}
    (output/'PROVENANCE.json').write_text(json.dumps(result,indent=2)+'\n')

if __name__ == '__main__':
    write(ROOT/'data/terrain/pbr')
